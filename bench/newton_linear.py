"""Paired CUDA solves of one actual contact Hessian, with a NumPy reference.

The checkpoint is generated by CPU MuJoCo. MJWarp assembles the first Newton
system from that checkpoint once. Every timed configuration receives the same
upper triangle and RHS; no simulation advances during timing.
"""
import argparse
from contextlib import ExitStack
from importlib.metadata import version
import json
from pathlib import Path
import sys
import time

import mujoco
import mujoco_warp as mjw
from mujoco_warp._src import solver
import numpy as np
import warp as wp

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / 'python'), str(ROOT / 'tools')]
from deform3d_warp.mujoco_contact import flex_contact_policy
from deform3d_warp.mujoco_metric import CooperativeMetricSolver
from deform3d_warp.mujoco_newton import ParallelNewtonSolver
from record_bag import drive


class _SystemCaptured(Exception):
    pass


def run(args):
    cpu_model = mujoco.MjModel.from_xml_path(str(args.scene.resolve()))
    cpu_model.opt.ccd_tolerance = args.cpu_ccd_tolerance
    cpu = mujoco.MjData(cpu_model)
    mujoco.mj_forward(cpu_model, cpu)
    for _ in range(round(args.time / cpu_model.opt.timestep)):
        drive(cpu_model, cpu)
        mujoco.mj_step(cpu_model, cpu)
    drive(cpu_model, cpu)
    with wp.ScopedDevice('cuda:0'):
        model = mjw.put_model(cpu_model)
        model.opt.ccd_tolerance.fill_(args.gpu_ccd_tolerance)
        data = mjw.put_data(cpu_model, cpu, nworld=args.worlds)
        metric = CooperativeMetricSolver(model, args.worlds)
        original = solver._cholesky_factorize_solve
        captured = {}

        def take_system(m, d, ctx, skip_unchanged=False, skip_noflip=False):
            captured['h'] = ctx.h.numpy()
            captured['g'] = ctx.grad.numpy()
            raise _SystemCaptured()

        with ExitStack() as setup:
            setup.enter_context(flex_contact_policy(model))
            setup.enter_context(metric.capture_policy())
            solver._cholesky_factorize_solve = take_system
            setup.callback(setattr, solver, '_cholesky_factorize_solve', original)
            try:
                mjw.forward(model, data)
            except _SystemCaptured:
                pass
        if not captured:
            raise RuntimeError('scene did not assemble a Newton system')
        if np.any(metric.status.numpy()):
            raise RuntimeError('checkpoint material solve failed')

        nv = model.nv
        # Only the upper triangle is defined by the upstream assembly contract.
        upper = np.triu(captured['h'][:, :nv, :nv]).astype(np.float64)
        matrix = upper + np.swapaxes(np.triu(upper, 1), 1, 2)
        rhs = captured['g'][:, :nv].astype(np.float64)
        if args.save_system:
            args.save_system.parent.mkdir(parents=True, exist_ok=True)
            np.savez_compressed(args.save_system, matrix=matrix, rhs=rhs)
        reference = np.linalg.solve(matrix, rhs[..., None])[..., 0]
        eigenvalues = np.linalg.eigvalsh(matrix)
        if np.any(eigenvalues[:, 0] <= 0):
            raise RuntimeError('captured Newton Hessian is not positive definite')

        records = []
        for name, precision, tile, diagonal in (('upstream', None, None, 'tiled'),
                                      ('parallel_float32_tile32', 'float32', 32, 'tiled'),
                                      ('register_float32_tile32', 'float32', 32, 'register'),
                                      ('parallel_float64_tile16', 'float64', 16, 'tiled'),
                                      ('parallel_float64_tile32', 'float64', 32, 'tiled'),
                                      ('register_float64_tile32', 'float64', 32, 'register')):
            ctx = solver._create_solver_context(model, data, inplace_cholesky=False)
            ctx.h.assign(captured['h'])
            ctx.grad.assign(captured['g'])
            ctx.done.zero_()
            policy = (ParallelNewtonSolver(model, args.worlds, precision=precision, tile_size=tile, diagonal=diagonal)
                      if precision else None)

            def enqueue():
                if policy:
                    policy.enqueue(ctx, data.nefc, data.nefc)
                else:
                    original(model, data, ctx)

            enqueue()
            wp.synchronize_device('cuda:0')
            with wp.ScopedCapture() as capture:
                for _ in range(args.repeat):
                    enqueue()
            # Each graph owns independent inputs/outputs; replay order alternates
            # below so a monotonic clock/temperature drift does not favor a path.
            records.append(dict(name=name, graph=capture.graph, ctx=ctx,
                                policy=policy, cuda_ms=[], wall_ms=[]))

        start = wp.Event(enable_timing=True)
        end = wp.Event(enable_timing=True)
        for sample in range(args.samples):
            for record in records[::1 if sample % 2 == 0 else -1]:
                began = time.perf_counter()
                wp.record_event(start)
                wp.capture_launch(record['graph'])
                wp.record_event(end)
                elapsed = wp.get_event_elapsed_time(start, end)
                record['cuda_ms'].append(elapsed / args.repeat)
                record['wall_ms'].append((time.perf_counter() - began) * 1000 / args.repeat)

        report = {
            'scene': str(args.scene), 'checkpoint_s': float(cpu.time),
            'nv': nv, 'worlds': args.worlds, 'gpu': wp.get_device().name,
            'mujoco_version': mujoco.__version__, 'mujoco_warp_version': version('mujoco-warp'),
            'warp_version': wp.__version__, 'samples': args.samples, 'solves_per_sample': args.repeat,
            'cpu_ccd_tolerance': args.cpu_ccd_tolerance,
            'gpu_ccd_tolerance': args.gpu_ccd_tolerance,
            'scope': 'identical fixed GPU Newton Hessian/RHS; factorization and search direction only; '
                     'parallel paths include residual/status monitoring; excludes assembly, physics and rendering',
            'matrix_condition_2': (eigenvalues[:, -1] / eigenvalues[:, 0]).tolist(),
            'metric_status': metric.status.numpy().tolist(), 'results': {}}
        for record in records:
            ctx, policy = record['ctx'], record['policy']
            x = -ctx.search.numpy().astype(np.float64)
            residual = np.linalg.norm((matrix @ x[..., None])[..., 0] - rhs, axis=1)
            residual /= np.maximum(np.linalg.norm(rhs, axis=1), np.finfo(float).tiny)
            delta = np.linalg.norm(x-reference, axis=1) / np.maximum(np.linalg.norm(reference, axis=1), 1e-30)
            result = {key: {'median': float(np.median(record[key])),
                            'p95': float(np.percentile(record[key], 95))}
                      for key in ('cuda_ms', 'wall_ms')}
            result.update(relative_residual=residual.tolist(), relative_solution_delta=delta.tolist(),
                          status=policy.status.numpy().tolist() if policy else None,
                          reported_residual=policy.max_relative_residual.numpy().tolist() if policy else None)
            report['results'][record['name']] = result
            if policy:
                np.testing.assert_array_equal(policy.status.numpy(), 0)
                np.testing.assert_allclose(policy.max_relative_residual.numpy(), residual, rtol=1e-4, atol=1e-8)
            if not np.isfinite(x).all() or np.max(residual) > 1e-4:
                raise RuntimeError(f"{record['name']} failed the independent residual check")
            # Neither path is allowed to consume the original upper triangle.
            np.testing.assert_array_equal(np.triu(ctx.h.numpy()), np.triu(captured['h']))
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(json.dumps(report, indent=2) + '\n')
        print(json.dumps(report, indent=2))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--scene', type=Path, default=ROOT / 'examples/mujoco_bag_strong_ref.xml')
    parser.add_argument('--time', type=float, default=1.4)
    parser.add_argument('--worlds', type=int, default=1)
    parser.add_argument('--cpu-ccd-tolerance', type=float, default=1e-9)
    parser.add_argument('--gpu-ccd-tolerance', type=float, default=1e-8)
    parser.add_argument('--samples', type=int, default=30)
    parser.add_argument('--repeat', type=int, default=10)
    parser.add_argument('--save-system', type=Path, help='optional fixed Hessian/RHS archive for independent analysis')
    parser.add_argument('--output', type=Path, default=ROOT / 'results/newton_linear_reproduction.json')
    args = parser.parse_args()
    if not np.isfinite(args.time) or args.time < 0 or min(args.worlds, args.samples, args.repeat) < 1:
        parser.error('time must be finite and nonnegative; counts must be positive')
    if not np.isfinite([args.cpu_ccd_tolerance,args.gpu_ccd_tolerance]).all() or min(args.cpu_ccd_tolerance,args.gpu_ccd_tolerance) <= 0:
        parser.error('CCD tolerances must be finite and positive')
    run(args)
